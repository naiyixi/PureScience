import { spawn, type ChildProcessWithoutNullStreams } from 'node:child_process'
import { join } from 'node:path'
import type { SessionModeState } from '@agentclientprotocol/sdk'

import {
  resolvePermissionProfileApplication,
  type PermissionProfileApplication
} from '../acp/permission-profile-controller'
import type { PermissionProfileId } from '../../shared/permission-profiles'
import { openAiCompletionsBase } from '../settings/base-url'
import { augmentedPathEnv } from '../settings/shell-path'
import type { ResolvedProvider } from '../settings/provider-env'
import type {
  AgentFramework,
  AgentModelConfig,
  AgentSpawnInput,
  ModelConfigContext,
  SessionSetup,
  SessionSetupContext
} from './types'
import { renderAppMcpToolReferences } from './app-mcp-names'

// Hermes Agent ships its own ACP server (`hermes acp`), so unlike the community-adapter route there is no
// third-party adapter to detect or version-gate. Measured on 0.23.3 (docs/evidence/
// 2026-11-24-hermes-acp-handshake.md): a spec-shaped `initialize` comes back in 7.2 s with
// `protocolVersion: 1`, `agentInfo {name: hermes-agent}` and
// `agentCapabilities {loadSession, promptCapabilities.image, sessionCapabilities {fork, list, resume}}` —
// and no `mcpCapabilities`, which is why both MCP flags stay false rather than assumed.
export const hermesStorageDir = (storageRoot: string): string => join(storageRoot, 'hermes')

const HERMES_CONFIG_VERSION = 1

// Always single-quote so a model id such as `oss'120b` cannot end the scalar early; inner quotes double.
const yamlScalar = (value: string): string => `'${value.replace(/'/g, "''")}'`

export const buildHermesConfigYaml = (provider: ResolvedProvider): string => {
  const baseUrl = openAiCompletionsBase(provider)
  if (!baseUrl || !provider.model) {
    throw new Error('Hermes requires an OpenAI-compatible base URL and a model.')
  }
  // No api_key line on purpose: measured 2026-11-24 against a loopback fixture, a prompt turn completes
  // with the credential supplied through OPENAI_API_KEY alone (and also config-only), so the app takes the
  // env path and keeps plaintext credentials out of the generated file.
  //
  // Also no agent.system_prompt line: in Hermes that field carries the rendered personality text and its
  // own config migrations scrub it, so app guidance rides the ACP prompt path instead.
  return `${[
    '# Generated by PureScience for one agent process. Rewritten on every provider change.',
    `# config-version: ${HERMES_CONFIG_VERSION}`,
    'model:',
    "  provider: 'custom'",
    `  default: ${yamlScalar(provider.model)}`,
    `  base_url: ${yamlScalar(baseUrl)}`,
    "  api_mode: 'chat_completions'",
    'mcp_servers: {}',
    'memory:',
    '  memory_enabled: false',
    '  user_profile_enabled: false'
  ].join('\n')}\n`
}

export const hermesFramework: AgentFramework = {
  id: 'hermes',
  displayName: 'Hermes',

  // No compaction command was measured for this build, so the runtime's own summarisation applies.
  contextCompaction: { kind: 'framework-managed' },

  // No config-dir skill surface the app can provision was measured.
  supportsSkills: false,

  // Neither MCP flag is claimed: the measured initialize result carries no `mcpCapabilities`, so the app's
  // tools cannot be assumed reachable. Wiring app MCP needs its own reading first.
  acceptsStdioMcp: false,
  acceptsHttpMcp: false,

  supportsLiveEffortChange: false,

  // Hermes reaches OpenAI-compatible /v1/chat/completions endpoints through `model.provider: custom`.
  supportedApiTypes: ['openai'],

  spawn(input: AgentSpawnInput): ChildProcessWithoutNullStreams {
    // A pipx/pip console script is a shell shim on Windows, which Node cannot launch without a shell.
    const needsShell = process.platform === 'win32' && /\.(cmd|bat)$/i.test(input.executablePath)

    return spawn(
      needsShell ? `"${input.executablePath}"` : input.executablePath,
      ['acp', ...(input.args ?? [])],
      {
        env: { ...augmentedPathEnv(process.env), ...input.env },
        stdio: 'pipe',
        windowsHide: true,
        shell: needsShell
      }
    )
  },

  prepareModelConfig(provider: ResolvedProvider, ctx: ModelConfigContext): AgentModelConfig {
    const baseUrl = openAiCompletionsBase(provider)
    if (!baseUrl || !provider.key || !provider.model) {
      throw new Error('Hermes requires an OpenAI-compatible base URL, API key, and model.')
    }

    const dataRoot = hermesStorageDir(ctx.storageRoot)

    return {
      env: {
        // The app owns Hermes' whole data root, so the user's own ~/.hermes is never read or written.
        HERMES_HOME: dataRoot,
        // Sessions carry their own mcpServers (none today); this keeps Hermes from also reading an
        // inherited MCP configuration out of the data root.
        HERMES_ACP_SKIP_CONFIGURED_MCP: '1',
        OPENAI_BASE_URL: baseUrl,
        OPENAI_API_KEY: provider.key
      },
      configFiles: [
        {
          path: join(dataRoot, 'config.yaml'),
          mode: 0o600,
          content: buildHermesConfigYaml(provider)
        }
      ],
      sessionModel: provider.model
    }
  },

  buildSessionSetup(ctx: SessionSetupContext): SessionSetup {
    // The measured initialize result exposes no session `_meta` surface the app can rely on, so app
    // guidance rides the prompt prefix — the one path verified with a real prompt turn.
    const promptPrefix = [...ctx.systemPromptAppends, ...(ctx.turnPromptReminders ?? [])]
      .map((append) => renderAppMcpToolReferences('hermes', append))
      .filter(Boolean)
      .join('\n\n')

    return {
      ...(promptPrefix ? { promptPrefix } : {})
    }
  },

  mapPermissionProfile(
    profile: PermissionProfileId,
    modes: SessionModeState | null | undefined
  ): PermissionProfileApplication {
    // Hermes advertises no mode surface in the measured initialize result, so the app's broker owns every
    // permission decision.
    return resolvePermissionProfileApplication(profile, modes, {
      brokerEnforcesFullAccess: true
    })
  }
}
