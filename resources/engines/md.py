#!/usr/bin/env python3
"""Molecular dynamics (GROMACS) for the app's simulation path.

One subcommand, JSON on stdout:

  run --pdb IN.pdb --out DIR --gmx PATH [--steps N] [--temperature T] [--seed S]

What this pipeline actually does, in order — and it says so rather than implying more:

  pdb2gmx (amber99sb-ildn / tip3p) -> editconf (cubic, 1.0 nm) -> energy minimisation
  -> NVT production run at the requested temperature.

**Vacuum, not solvent.** No water box is built, so this is a fast, honest check that the engine runs
end to end on a real structure — not a production simulation. The caller states that on screen; a
number from a vacuum run must never be read as a solvated result.

Reproducibility, measured rather than assumed (2026-10-18, GROMACS 2025.4, ARM Mac):

  - 4 threads:           trajectory and final .gro differ between runs
  - -nt 1:               still differ
  - -nt 1 -ntomp 1 -dlb no: still differ

So this script does NOT claim byte-identical output, and neither should anything downstream. What it
reports instead is the honest pair: the *input fingerprint* (structure sha256 + every parameter that
determines the run + the engine version), which anyone can recompute, and a set of *reproducible
quantities* (frame count, mean temperature, mean potential energy) that two runs should agree on
within their own noise. The trajectory's own sha256 is reported as the identity of THIS artifact, not
as evidence it can be regenerated byte for byte.

Failures are named, and each one is a different situation:

  gmx-missing        the engine binary is not where the caller said
  pdb-unreadable     the input structure cannot be read
  topology-failed    pdb2gmx refused the structure (missing atoms, unknown residue, force field)
  minimisation-failed the energy minimisation did not converge or mdrun errored
  run-failed         the production mdrun errored; the engine's own lines are passed through
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

EM_MDP = """integrator = steep
emtol = 1000.0
emstep = 0.01
nsteps = 500
cutoff-scheme = Verlet
coulombtype = PME
rcoulomb = 1.0
rvdw = 1.0
pbc = xyz
"""


def _mdp(steps, temperature, seed):
    return f"""integrator = md
dt = 0.002
nsteps = {steps}
cutoff-scheme = Verlet
coulombtype = PME
rcoulomb = 1.0
rvdw = 1.0
tcoupl = V-rescale
tc-grps = System
tau-t = 0.1
ref-t = {temperature}
gen-vel = yes
gen-temp = {temperature}
gen-seed = {seed}
constraints = h-bonds
constraint-algorithm = lincs
pbc = xyz
nstxout-compressed = 500
"""


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _fail(code, message):
    print(json.dumps({"status": "error", "code": code, "message": message}))
    sys.exit(2)


def _tail(text, lines=4):
    return " | ".join([line for line in (text or "").strip().splitlines()][-lines:])


def _run(gmx, args, cwd):
    return subprocess.run([gmx, *args], capture_output=True, text=True, cwd=str(cwd))


def _energy_mean(edr, term, cwd, gmx):
    """One number from the energy file, read through the engine rather than parsed by hand."""
    out = cwd / f"{term.lower()}.xvg"
    completed = subprocess.run(
        [gmx, "energy", "-f", str(edr), "-o", str(out)],
        input=f"{term}\n\n",
        capture_output=True,
        text=True,
        cwd=str(cwd),
    )
    if not out.is_file():
        return None
    values = []
    for raw in out.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line[0] in "#@":
            continue
        parts = line.split()
        if len(parts) >= 2:
            try:
                values.append(float(parts[1]))
            except ValueError:
                continue
    if not values:
        return None
    return round(sum(values) / len(values), 4)


def run(args):
    gmx = Path(args.gmx)
    if not gmx.is_file():
        _fail("gmx-missing", f"no gmx binary at {gmx}")
    pdb = Path(args.pdb)
    if not pdb.is_file():
        _fail("pdb-unreadable", f"missing {pdb}")

    work = Path(args.out)
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True, exist_ok=True)
    (work / "em.mdp").write_text(EM_MDP, encoding="utf-8")
    (work / "md.mdp").write_text(_mdp(args.steps, args.temperature, args.seed), encoding="utf-8")

    version = _run(gmx, ["--version"], work)
    version_line = next(
        (line.strip() for line in (version.stdout or "").splitlines() if "GROMACS - gmx" in line),
        "unknown",
    )

    topology = _run(
        gmx,
        [
            "pdb2gmx",
            "-f",
            str(pdb),
            "-o",
            "conf.gro",
            "-p",
            "topol.top",
            "-i",
            "posre.itp",
            "-ff",
            "amber99sb-ildn",
            "-water",
            "tip3p",
            "-ignh",
        ],
        work,
    )
    if topology.returncode != 0 or not (work / "conf.gro").is_file():
        _fail("topology-failed", _tail(topology.stdout or topology.stderr))

    boxed = _run(
        gmx, ["editconf", "-f", "conf.gro", "-o", "box.gro", "-c", "-d", "1.0", "-bt", "cubic"], work
    )
    if boxed.returncode != 0:
        _fail("topology-failed", _tail(boxed.stderr or boxed.stdout))

    em_grompp = _run(
        gmx,
        ["grompp", "-f", "em.mdp", "-c", "box.gro", "-p", "topol.top", "-o", "em.tpr", "-maxwarn", "1"],
        work,
    )
    if em_grompp.returncode != 0:
        _fail("minimisation-failed", _tail(em_grompp.stderr or em_grompp.stdout))
    em = _run(gmx, ["mdrun", "-deffnm", "em", "-nt", "4"], work)
    if em.returncode != 0 or not (work / "em.gro").is_file():
        _fail("minimisation-failed", _tail(em.stderr or em.stdout))

    md_grompp = _run(
        gmx,
        ["grompp", "-f", "md.mdp", "-c", "em.gro", "-p", "topol.top", "-o", "md.tpr", "-maxwarn", "1"],
        work,
    )
    if md_grompp.returncode != 0:
        _fail("run-failed", _tail(md_grompp.stderr or md_grompp.stdout))
    md = _run(gmx, ["mdrun", "-deffnm", "md", "-nt", "4"], work)
    if md.returncode != 0 or not (work / "md.xtc").is_file():
        _fail("run-failed", _tail(md.stderr or md.stdout))

    stats = {
        "meanTemperature": _energy_mean(work / "md.edr", "Temperature", work, gmx),
        "meanPotential": _energy_mean(work / "md.edr", "Potential", work, gmx),
    }

    # Frame and atom counts from the trajectory itself, not from the step budget: a run that stopped
    # early must not be reported as if it produced every frame it was asked for. `gmx check` separates
    # frames with carriage returns, so the output is split on both — a naive splitlines() sees one line.
    check = _run(gmx, ["check", "-f", "md.xtc"], work)
    frames = None
    atoms = None
    check_text = ((check.stdout or "") + (check.stderr or "")).replace("\r", "\n")
    for raw in check_text.splitlines():
        line = raw.strip()
        if line.startswith("# Atoms"):
            try:
                atoms = int(line.split()[-1])
            except (ValueError, IndexError):
                atoms = None
        elif line.startswith("Last frame"):
            parts = line.split()
            if len(parts) >= 3:
                try:
                    frames = int(parts[2]) + 1
                except ValueError:
                    frames = None

    print(
        json.dumps(
            {
                "status": "ok",
                "engine": "gromacs",
                "engineVersion": version_line,
                "pdbSha256": _sha256(pdb),
                "steps": args.steps,
                "temperature": args.temperature,
                "seed": args.seed,
                "solvent": "vacuum",
                "forceField": "amber99sb-ildn",
                "waterModel": "tip3p",
                "frames": frames,
                "atoms": atoms,
                "finalStructure": {
                    "sha256": _sha256(work / "md.gro"),
                    "bytes": (work / "md.gro").stat().st_size
                },
                "trajectory": {
                    "sha256": _sha256(work / "md.xtc"),
                    "bytes": (work / "md.xtc").stat().st_size
                },
                "statistics": stats,
                # Stated in the payload, not only in the docs: this is what a second party can and
                # cannot reproduce without this machine.
                "reproducible": {
                    "inputFingerprint": True,
                    "byteIdenticalOutput": False,
                    "note": "MEASURED: GROMACS 2025.4 output differed between runs with 4 threads, with -nt 1, and with -nt 1 -ntomp 1 -dlb no. Compare frames and statistics, not digests."
                }
            }
        )
    )


def main():
    parser = argparse.ArgumentParser(description="molecular dynamics engine")
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("run", help="minimise and run a short NVT trajectory")
    p.add_argument("--pdb", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--gmx", required=True)
    p.add_argument("--steps", type=int, default=5000)
    p.add_argument("--temperature", type=float, default=300.0)
    p.add_argument("--seed", type=int, default=37)
    p.set_defaults(handler=run)
    args = parser.parse_args()
    args.handler(args)


if __name__ == "__main__":
    main()
